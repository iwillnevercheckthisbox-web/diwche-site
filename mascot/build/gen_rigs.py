#!/usr/bin/env python3
"""Write a rig for every panel that has been cut.

    python3 build/gen_rigs.py [--force]

Rigs are generated rather than hand-written because the layer list comes out of the cut and
would otherwise have to be kept in step by hand across twelve files. What each rig says is
almost the same every time — that is the point. One character, one way of moving.

The amounts are deliberately small. He is a tired creature and the animation should be
noticed on second glance, not first: about half a percent of breath, half a degree of head
drift, a pixel and a half of float on the bubbles. Blink timings are staggered panel by panel
so a page showing several of them never blinks in chorus.
"""
from __future__ import annotations

import json
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).parent))

from _scenes import BY_SLUG as SCENE_BY_SLUG  # noqa: E402
from panels import PANELS                     # noqa: E402

ROOT = pathlib.Path(__file__).resolve().parent.parent

# Uneven on purpose: evenly spaced blinks read as a metronome, and identical timings across
# panels make a grid of them pulse together.
BLINKS = {
    1: [0.28, 0.74], 2: [0.19, 0.66], 3: [0.35, 0.81], 4: [],
    5: [0.31, 0.77], 6: [0.22, 0.63], 7: [], 8: [],
    9: [0.26, 0.72], 10: [0.33, 0.79], 11: [0.21, 0.68], 12: [],
}


def build(cfg, layers):
    num, slug = cfg["num"], cfg["slug"]
    scene = SCENE_BY_SLUG[slug]
    rig = {
        "scene": slug,
        "framing": scene["rig"],
        "loop_seconds": scene["loop"],
        "camera_push": 0,
        "accents": "none",
        "_note": ("A transparent cutout: the character and his thought bubble, no background. "
                  "Generated by build/gen_rigs.py from the layers the cut produced. Layer "
                  "positions come from where each part sat in the original drawing, so no "
                  "`pos` is given; anchors are fractions of each layer's own box."),
        "layers": {},
    }
    L = rig["layers"]

    L["body"] = {"anchor": [0.5, 1.0],
                 "motion": {"breathe": {"amp": 0.6, "cycles": 2}}}
    L["head"] = {"anchor": [0.5, 0.94], "parent": "body",
                 "motion": {"bob": {"deg": 0.5, "cycles": 1}}}

    if "eyes-closed" in layers:
        at = BLINKS.get(num, [0.3, 0.75])
        if at:
            L["eyes-closed"] = {"anchor": [0.5, 0.5], "parent": "head",
                                "motion": {"blink": {"closed": True, "at": at, "dur": 5}}}
        # Four keep no blink: 8 is too pleased with himself, and 4, 7 and 12 are drawn with
        # skin so close in tone to their eye-whites that a painted lid reads as a patch.

    for i, side in enumerate(("l", "r")):
        name = f"bubble-{side}"
        if name not in layers:
            continue
        L[name] = {"anchor": [0.5, 0.5],
                   "motion": {"sway": {"px": 1.5, "cycles": 1 + i}}}
        icons = f"icons-{side}"
        if icons in layers:
            L[icons] = {"anchor": [0.5, 0.5], "parent": name,
                        "motion": {"sway": {"px": 1.0, "cycles": 2 + i}}}
    return rig


def main(argv):
    force = "--force" in argv
    written = skipped = 0
    for cfg in PANELS:
        slug = f"{cfg['num']:02d}-{cfg['slug']}"
        meta_path = ROOT / "art" / slug / "layers.json"
        if not meta_path.exists():
            print(f"  {slug}: not cut yet")
            continue
        layers = {k for k in json.loads(meta_path.read_text()) if not k.startswith("_")}
        path = ROOT / "rig" / f"{slug}.rig.json"
        if path.exists() and not force:
            skipped += 1
            continue
        path.write_text(json.dumps(build(cfg, layers), indent=2) + "\n")
        written += 1
        print(f"  wrote {path.name}  ({len(build(cfg, layers)['layers'])} layers)")
    if skipped:
        print(f"  skipped {skipped} existing rig(s) — pass --force to regenerate")


if __name__ == "__main__":
    main(sys.argv)
